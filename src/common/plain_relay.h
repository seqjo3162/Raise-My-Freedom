#ifndef PLAIN_RELAY_H
#define PLAIN_RELAY_H

// Простой TCP-релей без модификации TLS. Общий код для модулей, которым нужно
// перенаправить 443 на локальный порт: у каждого модуля свой порт, свой
// SO_MARK и свои настройки, поэтому общий код не создаёт конфликтов между
// модулями. Правки sni_relay.c на него не влияют.
//
// Назначение — принять соединение, перенаправленное iptables на
// 127.0.0.1:<port>, и перелить его на оригинальный адрес назначения.
// ClientHello уходит байт в байт: разрыв SNI на этой сети приводит к тому,
// что поток к Cloudflare встаёт примерно на 20 КБ (измерено 2026-09-25).

#include <stddef.h>

typedef struct {
    int port;               // порт прослушивания на 127.0.0.1
    unsigned int so_mark;   // SO_MARK для исходящих сокетов (защита от петли)
    int chunk;              // порция пересылки, 0 = без ограничения
    int pause_ms;           // пауза между порциями, 0 = без паузы
    int idle_sec;           // таймаут простоя, 0 = ждать бесконечно
    // Разрыв SNI в ClientHello. Нужен там, где провайдер режет по имени
    // домена: измерено 2026-09-25, что к 162.159.138.232 handshake проходит с
    // SNI=api.vrchat.cloud и не проходит с SNI=discord.com.
    int split_client_hello; // 1 = разорвать SNI между двумя TLS-записями
    int frag_delay_ms;      // пауза между частями, 0 = не разрывать
    int frag_first_seg;     // размер первой части, 0 = 20
    // Дробление записей с данными. Провайдер собирает TLS-записи и обрывает
    // поток на границе первой полной записи (измерено: ровно 16384 + 17 байт
    // на discord.com/app), поэтому записи режутся на мелкие части — тогда
    // пересобрать поток по объёму не получается.
    int split_data_records; // 1 = дробить записи 0x17
    int split_record_size;  // размер части в байтах, 0 = 512
    int split_record_delay_ms; // пауза между частями, 0 = без паузы
} plain_relay_config_t;

int plain_relay_start(const plain_relay_config_t *cfg);
void plain_relay_stop(void);
int plain_relay_running(void);
int plain_relay_pid(void);

#endif
