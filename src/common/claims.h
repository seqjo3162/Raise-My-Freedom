#ifndef RMF_CLAIMS_H
#define RMF_CLAIMS_H

// Реестр IP, которые уже занял какой-то модуль.
//
// Каждый модуль, который собирается перехватывать трафик к своему адресу,
// записывает список своих IP в /run/rmf/claims/<модуль>. Перед добавлением
// правила модуль спрашивает реестр и пропускает адреса, занятые другими:
// так два модуля не ставят друг другу противоречащие REDIRECT на один IP.
//
// Каталог в /run — временный, после перезагрузки исчезает, поэтому ничего
// не восстанавливается и не расходится с реальным состоянием iptables.

#include <stddef.h>

// Объявить свои адреса. Один адрес — одна строка.
int claims_store(const char *module, const char *const *ips, size_t count);

// Занят ли адрес другим модулем (не тем, кто спрашивает).
int claims_taken_by_other(const char *module, const char *ip);

// Снять свою запись.
void claims_release(const char *module);

#endif
