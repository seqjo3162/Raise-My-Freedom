#ifndef RMF_SITE_PROBE_H
#define RMF_SITE_PROBE_H

// Проверка достижимости сайта. Нужна, чтобы модуль сам выбирал режим, а не
// полагался на ручную настройку:
//
//   site_probe_tcp — доходит ли TCP до адреса. Если нет, адрес отброшен
//                   провайдером, рель тут не поможет в принципе.
//   site_probe_sni — отвечает ли сервер на ClientHello с этим SNI. Молчание
//                   означает, что режут по имени домена, и тогда нужен рель
//                   с разрывом SNI. Любой ответ (в том числе alert) означает,
// что имя видно и рель не нужен.

// Пометить исходящие сокеты проверки, чтобы они не попадали в собственные
// REDIRECT-правила модуля. Без этого проба измеряет рель, а не провайдера.
void site_probe_set_mark(unsigned int mark);

int site_probe_tcp(const char *ip, int port, int timeout_ms);

// 1 — сервер ответил (SNI виден), 0 — тишина (SNI режут), -1 — нет соединения
int site_probe_sni(const char *ip, const char *hostname, int timeout_ms);

// Проверка имени в сертификате. Нужна, чтобы отличить «домен режут по имени»
// от «адрес принадлежит чужому серверу».
//
// Случай с Hugging Face: закреплён был 3.161.105.31, который с тех пор
// обслуживает Amazon и отдаёт CN=dp-contacts-opf.amazon.com. На TCP отвечает,
// TLS завершает, поэтому и site_probe_tcp, и site_probe_sni считали его
// живым, и пин оставался в силе, пока CDN файлов не отдавал мусор.
//
// Возвращает: 1 — сертификат выдан именно этому имени; 0 — рукопожатие
// прошло, но имя не совпало (адрес чужой); -1 — рукопожатие не завершилось
// (режут по имени или сервер молчит).
int site_probe_cert_ok(const char *ip, const char *hostname, int timeout_ms);

#endif
