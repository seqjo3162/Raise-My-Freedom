#!/usr/bin/env bash
# Захват реального трафика VRChat во время появления ошибки в клиенте.
#
# Зачем. Проверки через curl проходят идеально: 17 из 17 аватаров и 3 из 3
# миров скачиваются, метаданные и картинки тоже. Значит наш сетевой путь
# исправен, а «Error» рождается либо в самом клиенте, либо в том, как клиент
# обращается к сети. curl повторяет только наш собственный путь, но не путь
# клиента. Единственный способ увидеть настоящий запрос — посмотреть на него.
#
# Что делает. Снимает DNS-запросы, SNI из TLS и TCP-соединения к адресам
# VRChat, затем печатает сводку: какие хосты клиент спрашивал, какие адреса
# использовал и куда подключался. Ничего не блокирует и не меняет — только
# наблюдает, поэтому безопасно запускать прямо во время игры.
#
# Требует только tcpdump с sudo, полный root не нужен.
#
# Использование:
#   ./scripts/vrchat-trace.sh 60            # снимать 60 секунд
#   ./scripts/vrchat-trace.sh 300 out.pcap  # снимать 5 минут с сохранением
#
# Что делать параллельно: в этот же момент включить аватар, который
# показывает Error. Скрипт остановится сам и напечатает сводку.

set -u
DUR="${1:-60}"
OUT="${2:-/tmp/vrchat-trace-$$.pcap}"
# Фильтр намеренно широкий. Раньше здесь стоял список пиновых адресов, и
# захват выходил пустым: клиент идёт на ЧУЖИЕ адреса Cloudflare, которых в
# списке не было, — а именно это и требовалось увидеть. Поэтому снимаем весь
# DNS и все соединения на 443, а разбор идёт после, с проверкой «наш или нет».
VR="104.18.26.36 or 104.18.6.156 or 104.16.241.118 or 143.204.238.0/24 or 108.157.229.0/24 or 216.198.53.0/24 or 100.56.186.228"
BPF="(udp port 53) or (tcp port 443) or (udp port 443)"
# Адреса, на которых клиент обязан сидеть по нашим пинам.
OUR="104.18.26.36"

T() { sudo -n timeout "$@" 2>/dev/null; }

if ! sudo -n true 2>/dev/null && ! sudo -n tcpdump -D >/dev/null 2>&1; then
  echo "нужен sudo без пароля для tcpdump"
  exit 1
fi

echo "снимаю ${DUR} с -> ${OUT}"
echo "сейчас включи аватар, который показывает Error, и жди"
echo

T "$DUR" tcpdump -i any -nn -l -w "$OUT" "$BPF" >/dev/null

if [[ ! -s "$OUT" ]]; then
  echo "захват пустой: за ${DUR} с к адресам VRChat никто не обращался."
  echo "Значит клиент ходит в сеть в обход этой машины — скажи об этом,"
  echo "и будем искать другой путь."
  exit 1
fi

echo "захват: $(du -h "$OUT" | cut -f1)"
echo

echo "=== 1. DNS: какие имена спрашивал клиент ==="
T tcpdump -r "$OUT" -nn 2>/dev/null \
  | grep -oE 'A\? [A-Za-z0-9._-]+\.(vrchat\.(com|cloud)|vrcdn\.[a-z]+)' \
  | awk '{print $2}' | sort | uniq -c | sort -rn | head -20
T tcpdump -r "$OUT" -nn 2>/dev/null | grep -q 'vrchat' \
  || echo "  запросов к vrchat в DNS не было — клиент использует свой DoH"

echo
echo "=== 2. SNI: какие хосты клиент открывает по TLS ==="
T tcpdump -r "$OUT" -nn -A 2>/dev/null \
  | grep -oiE 'Host: [A-Za-z0-9._-]+\.vrchat[A-Za-z0-9.-]*' \
  | awk '{print $2}' | sort | uniq -c | sort -rn | head -20
T tcpdump -r "$OUT" -nn -A 2>/dev/null | grep -qi 'Host:.*vrchat' \
  || echo "  SNI в открытом виде не читается — смотри пункт 3"

echo
echo "=== 3. TCP: кто и куда подключается ==="
T tcpdump -r "$OUT" -nn 2>/dev/null | grep 'Flags \[S\]' \
  | grep -oE '^[0-9:.]+\.[0-9]+ > [0-9.]+' | awk '{print $1, $3}' \
  | sort | uniq -c | sort -rn | head -20

echo
echo "=== 4. Адреса назначения: куда клиент идёт на 443 ==="
T tcpdump -r "$OUT" -nn 2>/dev/null | grep 'Flags \[S\]' \
  | grep -oE '> [0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\.443' | awk '{print $2}' \
  | sort | uniq -c | sort -rn | head -15

echo
echo "=== 5. Пакеты без ответа (обрывы) ==="
T tcpdump -r "$OUT" -nn 2>/dev/null | grep -cE 'Flags \[R\]' \
  | sed 's/^/  RST (разрыв соединения): /'

echo
echo "=== 6. ГЛАВНОЕ: куда клиент идёт из наших пинов ==="
# Cloudflare anycast: один и тот же пул адресов обслуживает все хосты по SNI,
# поэтому клиент может уйти на соседний edge-узел и получить другой выход в
# интернет. Именно это рвёт сессию. Считаем, сколько соединений ушло мимо.
T tcpdump -r "$OUT" -nn 2>/dev/null | grep 'Flags \[S\]' \
  | grep -oE '> [0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\.443' | awk '{print $2}' \
  | sort | uniq -c | sort -rn > /tmp/vrchat-dest.$$ 2>/dev/null
echo "  наши пины (ожидаемо — правильный путь):"
grep -E "104\.18\.26\.36|143\.204\.238\.|108\.157\.229\.|104\.16\.241\.118" /tmp/vrchat-dest.$$ \
  | sed 's/^/    /' || echo "    нет ни одного — клиент полностью ушёл мимо"
echo "  ЧУЖИЕ адреса Cloudflare (подозрительно — другой выход в интернет):"
grep "104\.18\." /tmp/vrchat-dest.$$ | grep -v "104\.18\.26\.36" | sed 's/^/    /' \
  || echo "    нет"
rm -f /tmp/vrchat-dest.$$

echo
echo "полный файл: ${OUT}"
echo "копать глубже:  sudo -n tcpdump -r ${OUT} -nn -A | less"
